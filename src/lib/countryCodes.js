// Get country code by country code string
export const getCountryByCode = (code) => {
  return countryCodes.find(c => c.code === code);
};

// Get default country from IP
export const getDefaultCountryFromIP = async () => {
  try {
    const response = await fetch('https://ipapi.co/json/');
    const data = await response.json();
    if (data.country_code) {
      return getCountryByCode(data.country_code) || countryCodes[0]; // Default to US if not found
    }
  } catch (error) {
    console.error('Error fetching country from IP:', error);
  }
  return countryCodes[0]; // Default to US
};

